// Names for the layers. The keyboard has nowhere to store them, so they live in this browser, per keyboard.

import { useMemo } from 'react'
import { macroTitle, useDevice, type KeyboardData, type LinkInfo } from '../device'
import { getPref, setPref, usePref } from './prefs'
import { KEYCHRON_LAYERS_BY_MODEL, KEYCHRON_LAYERS_BY_UID } from '../device/keychron-layers'

const NONE: string[] = []
const key = (uid: string) => `layer-names:${uid}`

/** What identifies the keyboard for its default layer names. */
export type LayerIdentity = Pick<KeyboardData, 'uid' | 'definition'>

const hex4 = (n: number) => n.toString(16).padStart(4, '0')
function definitionId(value: unknown): number | null {
  const n = typeof value === 'string' ? Number(value) : typeof value === 'number' ? value : NaN
  return Number.isInteger(n) && n > 0 && n <= 0xffff ? n : null
}

/**
 * Compatibility: Keychron's keymaps order their layers four different ways, and number pads have no Mac / Windows
 * pair (vial_qmk keyboards/keychron/<board>/keymaps/vial/keymap.c, `enum layers`); the table comes from
 * scripts/keychron-layers.mjs. Every other keyboard's layers are "Layer n".
 *
 * What each layer is for, as far as the app knows, from the Keychron keymaps in vial-qmk (device/keychron-layers.ts,
 * generated by scripts/keychron-layers.mjs); null where it doesn't know. Looked up by the Vial keyboard ID (exactly
 * that keymap), then by the model in the keyboard's definition (a keymap of the same model built elsewhere), then,
 * on the cable only, by the link's USB IDs (a receiver has its own). The first two read the same through a 2.4 GHz
 * receiver. Any other keyboard: nothing known, every layer "Layer n".
 */
export function knownLayerNames(keyboard: LayerIdentity | null, link: LinkInfo | null): readonly (string | null)[] {
  if (!keyboard) return NONE
  const byUid = KEYCHRON_LAYERS_BY_UID[keyboard.uid.toLowerCase()]
  if (byUid) return byUid
  const definition = keyboard.definition as unknown as Record<string, unknown>
  const vendor = definitionId(definition.vendorId)
  const product = definitionId(definition.productId)
  if (vendor !== null && product !== null) return KEYCHRON_LAYERS_BY_MODEL[`${hex4(vendor)}:${hex4(product)}`] ?? NONE
  if (link?.kind === 'cable') return KEYCHRON_LAYERS_BY_MODEL[`${hex4(link.vendorId)}:${hex4(link.productId)}`] ?? NONE
  return NONE
}

/** A layer's default name: what the keymap says it is for, otherwise "Layer n". */
export function defaultLayerName(index: number, known: readonly (string | null)[]): string {
  return known[index] ?? `Layer ${index}`
}

/** The name of every layer: the user's where set, otherwise the default. */
export function useLayerNames(keyboard: KeyboardData | null, link: LinkInfo | null): string[] {
  const [stored] = usePref<string[]>(key(keyboard?.uid ?? ''), NONE)
  const count = keyboard?.layers ?? 0
  const known = useMemo(() => knownLayerNames(keyboard, link), [keyboard, link])
  return useMemo(
    () => Array.from({ length: count }, (_, i) => stored[i]?.trim() || defaultLayerName(i, known)),
    [stored, count, known],
  )
}

/** The layer names of the connected keyboard; empty when none is connected. */
export function useConnectedLayerNames(): string[] {
  const keyboard = useDevice((s) => s.keyboard)
  const link = useDevice((s) => s.link)
  return useLayerNames(keyboard, link)
}

/** The names as stored for a keyboard: what the user typed, empty where the default applies. For backups. */
export function storedLayerNames(uid: string): string[] {
  return getPref<string[]>(key(uid), NONE)
}

/** Replaces every stored name for a keyboard at once (a restore); empty names mean the default. */
export function setLayerNames(uid: string, names: string[]): void {
  setPref(key(uid), names.map((name) => name.trim()))
}

/** Names a layer; an empty name goes back to the default. */
export function renameLayer(uid: string, index: number, name: string): void {
  const names = [...getPref<string[]>(key(uid), NONE)]
  while (names.length <= index) names.push('')
  names[index] = name.trim()
  setPref(key(uid), names)
}

// Macro names: the same idea, kept per QMK index. A macro without one is called by QMK's number: "Macro 1" is M1,
// "Macro 0" is M0 (device/keycodes.ts, macroTitle).

const macroKey = (uid: string) => `macro-names:${uid}`

export const defaultMacroName = (index: number): string => macroTitle(index)

/** The names the user gave the connected keyboard's macros, as stored ("" where none was given). */
export function useStoredMacroNames(): string[] {
  const uid = useDevice((s) => s.keyboard?.uid ?? '')
  return usePref<string[]>(macroKey(uid), NONE)[0]
}

export function storedMacroNames(uid: string): string[] {
  return getPref<string[]>(macroKey(uid), NONE)
}

/** Replaces every stored macro name for a keyboard at once (a restore). */
export function setMacroNames(uid: string, names: string[]): void {
  setPref(macroKey(uid), names.map((name) => name.trim()))
}

/** Names a macro; an empty name goes back to the default. */
export function renameMacro(uid: string, index: number, name: string): void {
  const names = [...getPref<string[]>(macroKey(uid), NONE)]
  while (names.length <= index) names.push('')
  names[index] = name.trim()
  setPref(macroKey(uid), names)
}
